bicycles = ['trek', 'cannondale', 'redline', 'specialized']
print(bicycles) # output is presented as is stored; you usually don't want a user to see your output this way
print(bicycles[0]) # output just the first item in the list
print(bicycles[0].title()) # using string styles on the output to format it to 'Trek' when outputed
print(bicycles[-1]) # special index for outputing the last item of a list.
